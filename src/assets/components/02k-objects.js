/* ==========================================================================
   An object library for described scenery: everyday things as data, each
   a list of layers in its own box (x across, y down, units of 0.001 of the
   short side at its default size, the base at the bottom), stretched to
   the piece's w × h — a wider w makes a fatter jar, a taller h a taller
   clock. Placed like any piece: { part: 'samovar', x, w?, h?, layer?,
   color?, color2?, flip?, on?, y? }; hanging things (hang) take top (0..1
   of H) instead of standing on the floor.

   Layer: [path, token] fills, [path, token, width] strokes, [path, token,
   'eo'] fills even-odd. Tokens: c / cd / cl (color, darker, lighter),
   c2 / c2d / c2l (color2), the scene's wood and leaf, and fixed ones
   (metal, ink, glass, fire…) that follow the night; fire, flame, glow and
   screen keep their light, and a glow: [x, y, r] lights the dark.
   ========================================================================== */

const swO = (x, y, r) => `M${x - r} ${y} a${r} ${r} 0 1 0 ${2 * r} 0 a${r} ${r} 0 1 0 ${-2 * r} 0 Z`;
const swE = (x, y, rx, ry) => `M${x - rx} ${y} a${rx} ${ry} 0 1 0 ${2 * rx} 0 a${rx} ${ry} 0 1 0 ${-2 * rx} 0 Z`;
const swB = (x, y, w, h, r) => {
  r = Math.min(r || 0, w / 2, h / 2);
  if (!r) return `M${x} ${y} h${w} v${h} h${-w} Z`;
  return `M${x + r} ${y} H${x + w - r} Q${x + w} ${y} ${x + w} ${y + r} V${y + h - r} Q${x + w} ${y + h} ${x + w - r} ${y + h} H${x + r} Q${x} ${y + h} ${x} ${y + h - r} V${y + r} Q${x} ${y} ${x + r} ${y} Z`;
};
